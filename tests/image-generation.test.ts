import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { createCanvas } from "@napi-rs/canvas";
import type { AssistantImages, Models } from "@earendil-works/pi-ai";
import { generateVisualImage } from "../src/agent/image-generation.ts";

const selection = { provider: "openrouter", id: "image-fixture" };
const model = { provider: selection.provider, id: selection.id, name: "Image fixture", type: "image", output: ["image"] };
const usage = { input: 2, output: 3, cacheRead: 0, cacheWrite: 0, totalTokens: 5, cost: { input: 0, output: 0.1, cacheRead: 0, cacheWrite: 0, total: 0.1 } };

function client(result: AssistantImages, seen?: { prompt?: string }) {
	return {
		getModelOfType: ((type: string, provider: string, id: string) => type === "image" && provider === selection.provider && id === selection.id ? model : undefined) as Models["getModelOfType"],
		generateImages: (async (_model, context) => {
			seen && (seen.prompt = context.input[0]?.type === "text" ? context.input[0].text : undefined);
			return result;
		}) as Models["generateImages"],
	};
}

function response(output: AssistantImages["output"]): AssistantImages {
	return { api: "openai-completions", provider: selection.provider, model: selection.id, output, stopReason: "stop", usage, timestamp: 1 };
}

describe("generated visual images", () => {
	it("requires an explicit selection and a real image model", async () => {
		await assert.rejects(generateVisualImage("an illustration", undefined), /Image generation is not configured/);
		await assert.rejects(generateVisualImage("an illustration", { provider: "openrouter", id: "missing" }, { models: client(response([])) }), /No image model "missing"/);
	});

	it("surfaces provider failures and missing image output", async () => {
		await assert.rejects(generateVisualImage("an illustration", selection, { models: client({ ...response([]), stopReason: "error", errorMessage: "provider unavailable" }) }), /provider unavailable/);
		await assert.rejects(generateVisualImage("an illustration", selection, { models: client(response([{ type: "text", text: "no picture" }])) }), /returned no image/);
	});

	it("honors an already-aborted request without calling the provider", async () => {
		const controller = new AbortController();
		controller.abort(new Error("stopped"));
		let called = false;
		const models = client(response([]));
		const generate = models.generateImages;
		models.generateImages = (async (...args) => { called = true; return generate(...args); }) as Models["generateImages"];
		await assert.rejects(generateVisualImage("an illustration", selection, { models, signal: controller.signal }), /stopped/);
		assert.equal(called, false);
	});

	it("normalizes generated bytes and retains prompt, model, and usage", async () => {
		const png = createCanvas(8, 6).toBuffer("image/png");
		const seen: { prompt?: string } = {};
		const result = await generateVisualImage("a clean scientific illustration", selection, { models: client(response([{ type: "image", mimeType: "image/png", data: png.toString("base64") }]), seen) });
		assert.equal(seen.prompt, "a clean scientific illustration");
		assert.equal(result.image.path, "Generated illustration");
		assert.equal(result.image.width, 8);
		assert.equal(result.image.height, 6);
		assert.deepEqual(result.generated, { provider: selection.provider, model: selection.id, prompt: "a clean scientific illustration" });
		assert.deepEqual(result.usage, usage);
	});

	it("rejects malformed image bytes instead of storing them", async () => {
		await assert.rejects(generateVisualImage("an illustration", selection, { models: client(response([{ type: "image", mimeType: "image/png", data: "bm90IGFuIGltYWdl" }])) }), /Not a supported image/);
	});
});
